import { test } from "node:test";
import assert from "node:assert/strict";
import { parseLogLines, type LogEntry } from "../src/claude-log";
import { ExchangeBuilder, type Exchange } from "../src/panel/exchanges";
import { phaseOf, STALE_EXCHANGE_MS } from "../src/panel/phase";
import { build, fixture, lines, SESSION } from "./panel-helpers";

const NOW = Date.parse("2026-11-28T12:00:00Z");
const MINUTE = 60 * 1000;

function only(entries: LogEntry[]): Exchange {
  const all = build(entries).exchanges();
  assert.equal(all.length, 1);
  return all[0];
}

/** Ended or working with the file quiet just now (not stale). */
const phaseNow = (exchange: Exchange) => phaseOf(exchange, NOW, NOW);

/** A comparable snapshot: Sets and Maps as arrays. */
function snapshot(builder: ExchangeBuilder): unknown {
  return builder.exchanges().map((e) => ({ ...e, entryIds: [...e.entryIds], calls: [...e.calls.entries()] }));
}

const at = (minute: number) => new Date(Date.parse("2026-11-28T10:00:00Z") + minute * MINUTE).toISOString();
const prompt = (uuid: string, text: string, minute = 0) => ({ type: "user", uuid, timestamp: at(minute), message: { content: text } });
const reply = (uuid: string, text: string, stop: string | null, minute = 0) => ({
  type: "assistant",
  uuid,
  timestamp: at(minute),
  message: { id: `msg-${uuid}`, model: "claude-test", stop_reason: stop, content: [{ type: "text", text }] },
});

test("exchange: id is the prompt uuid; text, model, offsets and every entry id are kept", () => {
  const entries = fixture("prompt-and-reply");
  const exchange = only(entries);
  assert.equal(exchange.id, "uuid-1");
  assert.equal(exchange.sessionId, SESSION);
  assert.match(exchange.prompt.text, /Should we cache sessions\?/);
  assert.equal(exchange.startOffset, entries[0].startOffset);
  assert.equal(exchange.endOffset, entries.at(-1)!.endOffset);
  assert.deepEqual([...exchange.entryIds], entries.map((e) => e.uuid));
  assert.ok(exchange.model);
  assert.deepEqual(exchange.parts.map((p) => p.type), ["text"], "thinking adds no part");
});

test("exchange: parts stay in log order and each call gets its result", () => {
  const exchange = only(fixture("multi-block-assistant"));
  assert.deepEqual(exchange.parts.map((p) => (p.type === "step" ? `step:${p.callId}` : "text")), ["text", "step:toolu_read", "text"]);
  const read = exchange.calls.get("toolu_read");
  assert.equal(read?.call.tool, "Read");
  assert.equal(read?.result?.toolUseId, "toolu_read");
});

test("exchange: a new prompt starts a new exchange; harness and meta lines don't", () => {
  const builder = build(
    lines(
      { type: "system", subtype: "init" },
      reply("before", "Claude Code notice before any prompt", "end_turn"),
      prompt("p1", "First question"),
      { type: "user", uuid: "meta", isMeta: true, message: { content: "Caveat: generated by a command" } },
      { type: "user", uuid: "note", origin: { kind: "task-notification" }, message: { content: "Background task finished" } },
      { type: "user", uuid: "reminder", message: { content: "<system-reminder>ignore</system-reminder>" } },
      reply("a1", "First answer", "end_turn"),
      prompt("p2", "Second question"),
      reply("a2", "Second answer", "end_turn")
    )
  );
  const [first, second] = builder.exchanges();
  assert.deepEqual(builder.exchanges().map((e) => e.id), ["p1", "p2"]);
  assert.deepEqual([...first.entryIds], ["p1", "a1"]);
  assert.deepEqual([...second.entryIds], ["p2", "a2"]);
  assert.equal(builder.exchangeOfEntry("a1")?.id, "p1");
  assert.equal(builder.exchangeOfEntry("before"), undefined, "entries before the first prompt belong to no exchange");
});

test("exchange: applying the same entries twice changes nothing", () => {
  const entries = fixture("edit-write-multiedit-notebook");
  const builder = build(entries);
  const before = snapshot(builder);
  assert.deepEqual(builder.apply(entries), []);
  assert.deepEqual(builder.apply(entries.slice(2, 5)), []);
  assert.deepEqual(snapshot(builder), before);
});

test("exchange: applying entries one at a time equals applying them at once", () => {
  for (const name of ["edit-write-multiedit-notebook", "ask-user-question-answered", "tool-denied", "multi-block-assistant"]) {
    const entries = fixture(name);
    const incremental = new ExchangeBuilder(SESSION);
    const changed = entries.map((entry) => incremental.apply([entry]));
    assert.deepEqual(snapshot(incremental), snapshot(build(entries)), name);
    assert.ok(changed.every((ids) => ids.length === 1 && ids[0] === "uuid-1"), `${name}: each entry reports its exchange`);
  }
});

test("exchange: a result for an unknown call is ignored and counted", () => {
  const builder = build(
    lines(prompt("p1", "Go"), { type: "user", uuid: "r1", message: { content: [{ type: "tool_result", tool_use_id: "toolu_missing", content: "ok" }] } })
  );
  const [exchange] = builder.exchanges();
  assert.equal(builder.orphanResults, 1);
  assert.equal(exchange.calls.size, 0);
  assert.deepEqual([...exchange.entryIds], ["p1"]);
});

test("phase: a finished reply is done; one with a pending call is working", () => {
  assert.deepEqual(phaseNow(only(fixture("prompt-and-reply"))), { phase: "ended", endReason: "done" });
  assert.deepEqual(phaseNow(only(fixture("ask-user-question-answered"))), { phase: "ended", endReason: "done" });
  const toolCallPending = fixture("multi-block-assistant").slice(0, 3); // tool_use written, no result yet
  assert.deepEqual(phaseNow(only(toolCallPending)), { phase: "working", endReason: null });
});

test("phase: an interrupt ends the exchange as stopped by the person, also after a denial", () => {
  assert.deepEqual(phaseNow(only(fixture("interrupt"))), { phase: "ended", endReason: "stoppedByUser" });
  assert.deepEqual(phaseNow(only(fixture("tool-denied"))), { phase: "ended", endReason: "stoppedByUser" });
});

test("phase: an API error notice ends it as an error, until Claude Code writes more", () => {
  const entries = fixture("api-error");
  const builder = build(entries);
  const [exchange] = builder.exchanges();
  assert.deepEqual(phaseNow(exchange), { phase: "ended", endReason: "error" });
  const end = entries.at(-1)!.endOffset;
  const retried = parseLogLines([JSON.stringify(reply("retry", "Done after a retry", null)), JSON.stringify(reply("retry-2", "All set.", "end_turn"))], end);
  builder.apply(retried.slice(0, 1));
  assert.deepEqual(phaseNow(exchange), { phase: "working", endReason: null });
  builder.apply(retried.slice(1));
  assert.deepEqual(phaseNow(exchange), { phase: "ended", endReason: "done" });
});

test("phase: quiet for 10 minutes is incomplete; once the file grows again (the caller moves quietSince) it is working", () => {
  const exchange = only(lines(prompt("p1", "Refactor it", 0), reply("a1", "Starting…", null, 1)));
  const quietSince = NOW - STALE_EXCHANGE_MS;
  assert.deepEqual(phaseOf(exchange, NOW - 1, quietSince), { phase: "working", endReason: null });
  assert.deepEqual(phaseOf(exchange, NOW, quietSince), { phase: "ended", endReason: "incomplete" });
  assert.deepEqual(phaseOf(exchange, NOW, NOW), { phase: "working", endReason: null });
});

test("phase: an unanswered AskUserQuestion is never stale: Claude Code is waiting for the person", () => {
  const exchange = only(fixture("ask-user-question-pending"));
  assert.deepEqual(phaseOf(exchange, NOW, NOW - 60 * MINUTE), { phase: "working", endReason: null });
});

const resultLine = (uuid: string, ...ids: string[]) => ({
  type: "user",
  uuid,
  message: { content: ids.map((id) => ({ type: "tool_result", tool_use_id: id, content: "ok" })) },
});
const toolUse = (uuid: string, id: string, tool: string, stop: string | null = "tool_use") => ({
  type: "assistant",
  uuid,
  message: { id: `msg-${uuid}`, model: "claude-test", stop_reason: stop, content: [{ type: "tool_use", id, name: tool, input: {} }] },
});

test("exchange: several entries from one line are all applied (two results; an interrupt and the next prompt)", () => {
  const builder = build(
    lines(
      prompt("p1", "Read both"),
      toolUse("a1", "t1", "Read"),
      toolUse("a2", "t2", "Read"),
      resultLine("r1", "t1", "t2"),
      reply("a3", "Read them.", "end_turn"),
      prompt("p2", "Now rewrite it"),
      reply("a4", "Rewriting…", null),
      {
        type: "user",
        uuid: "p3",
        message: { content: [{ type: "text", text: "[Request interrupted by user]" }, { type: "text", text: "Stop, use the old one" }] },
      }
    )
  );
  const [first, second, third] = builder.exchanges();
  assert.ok(first.calls.get("t1")?.result && first.calls.get("t2")?.result, "both results on one line attach");
  assert.deepEqual(phaseNow(first), { phase: "ended", endReason: "done" });
  assert.equal(second.interrupted, true);
  assert.equal(third?.id, "p3", "the prompt sharing the interrupt's line starts a new exchange");
  assert.equal(builder.exchangeOfEntry("p3")?.id, "p3");
  assert.equal(second.entryIds.has("p3"), false, "the uuid belongs to one exchange only");
  assert.equal(second.endOffset, third.startOffset, "the earlier exchange ends where the shared line starts");
});

test("exchange: a repeated prompt (resumed history) is skipped with everything after it, until a new prompt", () => {
  const builder = build(
    lines(
      prompt("p1", "Pick a cache"),
      reply("a1", "Redis.", "end_turn"),
      prompt("p2", "And the queue?"),
      prompt("p1", "Pick a cache"),
      reply("a1", "Redis.", "end_turn"),
      prompt("p3", "Ship it"),
      reply("a3", "Shipped.", "end_turn")
    )
  );
  assert.deepEqual(builder.exchanges().map((e) => e.id), ["p1", "p2", "p3"]);
  assert.equal(builder.exchangeOfEntry("a1")?.id, "p1");
  assert.deepEqual([...builder.exchanges()[1].entryIds], ["p2"]);
  assert.equal(builder.exchanges()[1].parts.length, 0);
});

test("exchange: entries without a uuid or timestamp are kept but not mapped, and keep the last known time", () => {
  const builder = build(lines(prompt("p1", "Go", 0), { type: "assistant", message: { model: "m", stop_reason: "end_turn", content: [{ type: "text", text: "Done." }] } }));
  const [exchange] = builder.exchanges();
  assert.deepEqual([...exchange.entryIds], ["p1"]);
  assert.equal(builder.exchangeOfEntry(""), undefined);
  assert.equal(exchange.lastEntryAt, at(0));
  assert.deepEqual(exchange.parts, [{ type: "text", text: "Done." }]);
});

test("exchange: prompts without a uuid each start their own exchange", () => {
  const entries = lines({ type: "user", message: { content: "First" } }, reply("a1", "One", "end_turn"), { type: "user", message: { content: "Second" } }, reply("a2", "Two", "end_turn"));
  const builder = build(entries);
  assert.deepEqual(builder.exchanges().map((e) => e.id), [`line:${entries[0].startOffset}`, `line:${entries[2].startOffset}`]);
  assert.deepEqual(builder.exchanges().map((e) => [...e.entryIds]), [["a1"], ["a2"]]);
});

test("phase: a reply marked finished but with a call still pending is working", () => {
  const exchange = only(lines(prompt("p1", "Run it"), toolUse("a1", "t1", "Bash", "end_turn")));
  assert.deepEqual(phaseNow(exchange), { phase: "working", endReason: null });
});

test("phase: an exchange replaced by a later prompt has ended, even with an unanswered question", () => {
  const builder = build(lines(prompt("p1", "Set it up"), toolUse("a1", "ask", "AskUserQuestion"), prompt("p2", "Never mind, do this")));
  const [replaced, latest] = builder.exchanges();
  assert.deepEqual(phaseNow(replaced), { phase: "ended", endReason: "incomplete" });
  assert.deepEqual(phaseNow(latest), { phase: "working", endReason: null });
});

test("phase: lines after an interrupt don't reopen it (unlike an API error)", () => {
  const exchange = only([...fixture("interrupt"), ...parseLogLines([JSON.stringify(reply("late", "Stopping.", "end_turn"))], fixture("interrupt").at(-1)!.endOffset)]);
  assert.deepEqual(phaseNow(exchange), { phase: "ended", endReason: "stoppedByUser" });
});
